"""Regenerates js/sheets/nonedu-pdf-spells.js from the 2014 fillable PDF.

The 2014 PDF's field names are meaningless ("Spells 1014", "Check Box 3031"), so we
match fields to spell levels/rows by their POSITION on page 3.
Needs pymupdf (pip install pymupdf). Run from the project root:
    python3 tools/gen_nonedu_spell_map.py
"""
import json, pymupdf
SRC = "assets/templates/character-sheet-2014.pdf"
OUT = "js/sheets/nonedu-pdf-spells.js"
d = pymupdf.open(SRC); W = list(d[2].widgets())
cols = {0: (40, 32), 1: (229, 221), 2: (416, 408)}      # column -> (text x, checkbox x)
levels = [(0,0,150,300),(1,0,350,520),(2,0,560,750),(3,1,160,350),(4,1,395,580),
          (5,1,620,750),(6,2,160,300),(7,2,335,470),(8,2,505,610),(9,2,645,750)]   # level, column, y range
spells = {}
for lvl, c, y0, y1 in levels:
    tx, cx = cols[c]
    names = sorted([w for w in W if w.field_name.startswith("Spells") and abs(w.rect.x0-tx) < 4 and y0 <= w.rect.y0 <= y1], key=lambda w: w.rect.y0)
    boxes = sorted([w for w in W if w.field_type_string == "CheckBox" and abs(w.rect.x0-cx) < 4 and y0 <= w.rect.y0 <= y1+6], key=lambda w: w.rect.y0)
    spells[lvl] = {"names": [w.field_name for w in names], "prepared": [w.field_name for w in boxes]}
    print(lvl, len(names), "spell lines,", len(boxes), "prepared boxes")
js = ("// GENERATED by tools/gen_nonedu_spell_map.py from the 2014 PDF (matched by field position).\n"
      "// For each spell level: the spell-name fields and prepared-checkboxes, top to bottom.\n"
      "const NONEDU_PDF_SPELLS = " + json.dumps(spells, indent=1) + ";\n")
open(OUT, "w").write(js); print("wrote", OUT)
